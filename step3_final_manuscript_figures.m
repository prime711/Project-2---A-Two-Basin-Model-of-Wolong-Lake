%% ================================================================
% 3. COUNT EQUILIBRIA
% ================================================================

stableCount = zeros(size(Wgrid));
totalCount  = zeros(size(Wgrid));

for iw = 1:length(Wgrid)

    W = Wgrid(iw);

    rows = abs(allEq(:,1)-W) < 1e-10;

    totalCount(iw) = sum(rows);

    stableCount(iw) = sum(allEq(rows,7)==1);

end


%% ================================================================
% 4. NUMBER OF STABLE EQUILIBRIA
% ================================================================

figure('Color','w','Position',[100 100 800 480]);

hold on;
box on;
grid on;

hStableCount = stairs( ...
    Wgrid, ...
    stableCount, ...
    'k-', ...
    'LineWidth',2.2, ...
    'DisplayName','Stable equilibrium count');

hSillCount = xline( ...
    p.zsill, ...
    '--', ...
    'Color',[0.5 0.5 0.5], ...
    'LineWidth',1.5, ...
    'DisplayName','Sill elevation');

xlabel('Water surface elevation (m)');
ylabel('Number of stable equilibria');

xlim([Wmin Wmax]);
ylim([0 1.5]);
yticks([0 0.5 1 1.5]);

set(gca,'FontSize',11, ...
        'LineWidth',1, ...
        'TickDir','out');

legend( ...
    [hStableCount hSillCount], ...
    {'Stable equilibrium count', ...
     'Sill elevation'}, ...
    'Location','southeast', ...
    'FontSize',10);

hold off;


