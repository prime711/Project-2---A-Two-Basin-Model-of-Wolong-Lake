%% ================================================================
% FINAL MANUSCRIPT FIGURES — NO CIRCLE MARKERS
% ================================================================

stableSort   = sortrows(stableEq,1);
unstableSort = sortrows(unstableEq,1);

% Sparse markers only for unstable equilibria
markerStep = 8;


%% ================================================================
% 1. A1 EQUILIBRIUM STRUCTURE
% ================================================================

figure('Color','w','Position',[100 100 800 520]);

hold on;
box on;
grid on;

% Stable equilibrium: SOLID LINE ONLY
hStableA = plot( ...
    stableSort(:,1), ...
    stableSort(:,2), ...
    'k-', ...
    'LineWidth',2.2, ...
    'DisplayName','Stable equilibrium');

% Unstable equilibrium: x markers
idxUnstable = 1:markerStep:size(unstableSort,1);

hUnstableA = plot( ...
    unstableSort(idxUnstable,1), ...
    unstableSort(idxUnstable,2), ...
    'kx', ...
    'MarkerSize',6, ...
    'LineWidth',1.2, ...
    'DisplayName','Non-stable equilibrium');

% Sill elevation
hSillA = xline( ...
    p.zsill, ...
    '--', ...
    'Color',[0.5 0.5 0.5], ...
    'LineWidth',1.5, ...
    'DisplayName','Sill elevation');

xlabel('Water surface elevation (m)');
ylabel('Equilibrium A_1 (\mug/L)');

xlim([Wmin Wmax]);
ylim([0 max(stableSort(:,2))*1.08]);

set(gca,'FontSize',11, ...
        'LineWidth',1, ...
        'TickDir','out');

legend( ...
    [hStableA hUnstableA hSillA], ...
    {'Stable equilibrium', ...
     'Non-stable equilibrium', ...
     'Sill elevation'}, ...
    'Location','southeast', ...
    'FontSize',10);

hold off;


